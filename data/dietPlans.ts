import type { DietPlan, PersonId, Slot } from "@/lib/types";

/**
 * Piani iniziali (dai PDF del nutrizionista, 15-16 settembre 2026).
 * Servono finché dall'app non importi un piano nuovo: il piano importato ha la precedenza.
 *
 * slot(id, fisso, ...alternative): la prima voce è l'alimento FISSO,
 * le altre sono le ALTERNATIVE con la grammatura equivalente indicata dal nutrizionista.
 * days[0] = Lunedì ... days[6] = Domenica. Per Antonio: Lun-Gio = giorni ON, Ven-Dom = giorni OFF.
 */
function slot(id: string, ...options: [name: string, grams: number][]): Slot {
  return {
    id,
    options: options.map(([name, grams], i) => ({ id: `${id}-${i}`, name, grams })),
  };
}

